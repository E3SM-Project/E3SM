module CompactLayoutMod
  !-----------------------------------------------------------------------
  ! !DESCRIPTION:
  ! Compact storage for subgrid fields that are only used on a filter.
  !
  ! Each field registered with a compact_buffer_type gets compact storage
  ! with the bounds of its full array (beg:end). Each clump uses the start of
  ! its own range: the fp-th element of the clump's soil patch filter is
  ! element compact_soilp_off + fp, where compact_soilp_off is begp-1 of the
  ! clump (set by get_clump_bounds).
  !
  ! The original (full layout) allocation of each field is kept. History and
  ! restart point at it; unpack copies the compact values of the filter's
  ! elements into it, pack copies them back.
  !
  !   call buf%init(begp, endp)
  !   call buf%add(compact_field('leaf_mr', class=1, unpack=.true.), this%leaf_mr)
  !   ...                  ! this%leaf_mr now points at its compact storage
  !   call buf%full_view(this%leaf_mr)       ! back to the full layout
  !   call buf%compact_view(this%leaf_mr)    ! and to the compact storage
  !   write(iulog,*) buf                     ! the fields, by zeroing class
  !
  ! The derived types that use this module, and the routines that index their
  ! fields with compact_soilp_off, are generated by `spel compact rewrite`.
  !
  ! !USES:
  use shr_kind_mod, only : r8 => shr_kind_r8
  use shr_sys_mod , only : shr_sys_abort  ! not endrun: decompMod uses this module
  !
  implicit none
  private
  !
  ! begp-1 of the clump being computed
  integer, public :: compact_soilp_off = 0
  !$omp threadprivate(compact_soilp_off)

  type, public :: compact_field
     character(len=64) :: name = ''
     integer :: class = 0                     ! zeroing class
     logical :: unpack = .false.              ! copied to `full` at the unpack point
     real(r8), pointer :: full(:) => null()   ! full layout (original allocation)
     real(r8), pointer :: compact(:) => null()
  end type compact_field

  type, public :: compact_buffer_type
     integer :: beg = 1
     integer :: end = 0
     logical :: bound = .false.               ! the components point at the compact storage
     type(compact_field), allocatable :: fields(:)
   contains
     procedure, public :: init         => compact_init
     procedure, public :: add          => compact_add
     procedure, public :: compact_view => compact_compact_view
     procedure, public :: full_view    => compact_full_view
     procedure, public :: zero         => compact_zero
     procedure, public :: unpack       => compact_unpack
     procedure, public :: pack         => compact_pack
     procedure, public :: clean        => compact_clean
     procedure, private :: write_formatted => compact_write
     generic, public :: write(formatted) => write_formatted
  end type compact_buffer_type

  public :: compact_set_clump
  !-----------------------------------------------------------------------

contains

  !-----------------------------------------------------------------------
  subroutine compact_set_clump(begp)
    integer, intent(in) :: begp  ! first patch of the clump
    compact_soilp_off = begp - 1
  end subroutine compact_set_clump

  !-----------------------------------------------------------------------
  subroutine compact_init(this, beg, end)
    class(compact_buffer_type) :: this
    integer, intent(in) :: beg, end

    this%beg = beg
    this%end = end
    allocate(this%fields(0))
  end subroutine compact_init

  !-----------------------------------------------------------------------
  subroutine compact_add(this, field, ptr)
    ! Give `ptr` (a field's component, as allocated) compact storage, with its
    ! current values, and point it there. A field that isn't allocated is skipped.
    class(compact_buffer_type) :: this
    type(compact_field), intent(in) :: field
    real(r8), pointer, intent(inout) :: ptr(:)
    type(compact_field) :: f

    if (.not. associated(ptr)) return
    f = field
    f%full => ptr
    allocate(f%compact(this%beg:this%end))
    f%compact(:) = ptr(this%beg:this%end)
    ptr => f%compact
    this%fields = [this%fields, f]
    this%bound = .true.
  end subroutine compact_add

  !-----------------------------------------------------------------------
  subroutine compact_compact_view(this, ptr)
    ! Point `ptr` at its field's compact storage (no-op if it already does).
    class(compact_buffer_type) :: this
    real(r8), pointer, intent(inout) :: ptr(:)
    integer :: i

    do i = 1, size(this%fields)
       if (associated(ptr, this%fields(i)%full)) then
          ptr => this%fields(i)%compact
          return
       end if
    end do
  end subroutine compact_compact_view

  !-----------------------------------------------------------------------
  subroutine compact_full_view(this, ptr)
    ! Point `ptr` back at its field's full layout copy (no-op if it already does).
    class(compact_buffer_type) :: this
    real(r8), pointer, intent(inout) :: ptr(:)
    integer :: i

    do i = 1, size(this%fields)
       if (associated(ptr, this%fields(i)%compact)) then
          ptr => this%fields(i)%full
          return
       end if
    end do
  end subroutine compact_full_view

  !-----------------------------------------------------------------------
  subroutine compact_zero(this, class, num, filter, value)
    ! Set the fields of `class` to `value` on the clump's filter. Compact:
    ! `filter` must be the clump's soil patch filter (elements
    ! compact_soilp_off+1 .. compact_soilp_off+num).
    class(compact_buffer_type) :: this
    integer , intent(in) :: class
    integer , intent(in) :: num
    integer , intent(in) :: filter(:)
    real(r8), intent(in) :: value
    integer :: i

    if (num <= 0 .or. .not. allocated(this%fields)) return
    if (this%bound .and. compact_soilp_off + num > this%end) then
       call shr_sys_abort('CompactLayoutMod: compact_zero: filter longer than the clump')
    end if
    do i = 1, size(this%fields)
       if (this%fields(i)%class /= class) cycle
       if (this%bound) then
          this%fields(i)%compact(compact_soilp_off+1 : compact_soilp_off+num) = value
       else
          this%fields(i)%full(filter(1:num)) = value
       end if
    end do
  end subroutine compact_zero

  !-----------------------------------------------------------------------
  subroutine compact_unpack(this, num, filter, all)
    ! Copy the compact values of the clump's filter into the full layout
    ! copies of the fields marked `unpack` (every field if `all`).
    class(compact_buffer_type) :: this
    integer , intent(in) :: num
    integer , intent(in) :: filter(:)
    logical , intent(in), optional :: all
    integer :: i, fp
    logical :: every

    if (.not. allocated(this%fields)) return
    every = .false.
    if (present(all)) every = all
    do i = 1, size(this%fields)
       if (.not. (every .or. this%fields(i)%unpack)) cycle
       do concurrent (fp = 1:num)
          this%fields(i)%full(filter(fp)) = this%fields(i)%compact(compact_soilp_off + fp)
       end do
    end do
  end subroutine compact_unpack

  !-----------------------------------------------------------------------
  subroutine compact_pack(this, num, filter)
    ! Copy the full layout values of the clump's filter into compact storage.
    class(compact_buffer_type) :: this
    integer , intent(in) :: num
    integer , intent(in) :: filter(:)
    integer :: i, fp

    if (.not. allocated(this%fields)) return
    do i = 1, size(this%fields)
       do concurrent (fp = 1:num)
          this%fields(i)%compact(compact_soilp_off + fp) = this%fields(i)%full(filter(fp))
       end do
    end do
  end subroutine compact_pack

  !-----------------------------------------------------------------------
  subroutine compact_clean(this)
    ! Free the compact storage. The components must be on their full view
    ! (full_view) first; the full layout allocations are left to their owner.
    class(compact_buffer_type) :: this
    integer :: i

    if (.not. allocated(this%fields)) return
    do i = 1, size(this%fields)
       deallocate(this%fields(i)%compact)
    end do
    deallocate(this%fields)
    this%bound = .false.
  end subroutine compact_clean

  !-----------------------------------------------------------------------
  subroutine compact_write(dtv, unit, iotype, v_list, iostat, iomsg)
    ! write(unit, *) buf: the elements and the fields of each zeroing class
    class(compact_buffer_type), intent(in) :: dtv
    integer, intent(in) :: unit
    character(len=*), intent(in) :: iotype
    integer, intent(in) :: v_list(:)
    integer, intent(out) :: iostat
    character(len=*), intent(inout) :: iomsg
    character(len=:), allocatable :: text
    character(len=64) :: head
    character(len=1), parameter :: nl = new_line('a')
    integer :: i, c, n

    n = 0
    if (allocated(dtv%fields)) n = size(dtv%fields)
    write(head, '(i0,a,i0,a,i0)') n, ' fields on elements ', dtv%beg, ':', dtv%end
    text = 'compact buffer: '//trim(head)//', view: '//trim(merge('compact', 'full   ', dtv%bound))
    if (n > 0) then
       do c = minval(dtv%fields(:)%class), maxval(dtv%fields(:)%class)
          if (.not. any(dtv%fields(:)%class == c)) cycle
          write(head, '(i0)') c
          text = text//nl//'  zeroing class '//trim(head)//':'
          do i = 1, n
             if (dtv%fields(i)%class /= c) cycle
             text = text//nl//'    '//trim(dtv%fields(i)%name)//trim(merge(' (unpacked)', '           ', &
                  dtv%fields(i)%unpack))
          end do
       end do
    end if
    write(unit, '(a)', iostat=iostat, iomsg=iomsg) text
  end subroutine compact_write

end module CompactLayoutMod
