  subroutine column_nutrient_state_summary(this, num_soilc, filter_soilc)
    !
    ! !ARGUMENTS:
    type(column_nutrient_state), intent(inout) :: this
    integer                , intent(in)    :: num_soilc       ! number of soil columns in filter
    integer                , intent(in)    :: filter_soilc(:) ! filter for soil columns
    integer :: c, j, l
    integer :: fc
    real(r8) :: maxdepth        ! depth to integrate soil variables
    integer  :: nlev
    !-----------------------------------------------------------------------
    !-----------------------------------------------------------------------

    nlev = nlevdecomp

    ! vertically integrate each of the decomposing C pools
    do l = 1, ndecomp_pools
       do fc = 1,num_soilc
          c = filter_soilc(fc)
          this%decomp_pools(c,l) = 0._r8
       end do
    end do

    do l = 1, ndecomp_pools
       do j = 1, nlev
          do fc = 1,num_soilc
             c = filter_soilc(fc)
             this%decomp_pools(c,l) = &
                  this%decomp_pools(c,l) + &
                  this%decomp_pools_vr(c,j,l) * dzsoi_decomp(j)
          end do
       end do
    end do

    if ( nlevdecomp > 1) then
       ! vertically integrate each of the decomposing C pools to 1 meter
       maxdepth = 1._r8
       do l = 1, ndecomp_pools
          do fc = 1,num_soilc
             c = filter_soilc(fc)
             this%decomp_pools_1m(c,l) = 0._r8
          end do
       end do
       do l = 1, ndecomp_pools
          do j = 1, nlevdecomp
             if ( zisoi(j) <= maxdepth ) then
                do fc = 1,num_soilc
                   c = filter_soilc(fc)
                   this%decomp_pools_1m(c,l) = &
                        this%decomp_pools_1m(c,l) + &
                        this%decomp_pools_vr(c,j,l) * dzsoi_decomp(j)
                end do
             elseif ( zisoi(j-1) < maxdepth ) then
                do fc = 1,num_soilc
                   c = filter_soilc(fc)
                   this%decomp_pools_1m(c,l) = &
                        this%decomp_pools_1m(c,l) + &
                        this%decomp_pools_vr(c,j,l) * (maxdepth - zisoi(j-1))
                end do
             endif
          end do
       end do

       ! total litter carbon in the top meter (TOTLITC_1m)
       do fc = 1,num_soilc
          c = filter_soilc(fc)
          this%totlit_1m(c)         = 0._r8
       end do
       do l = 1, ndecomp_pools
          if ( decomp_cascade_con%is_litter(l) ) then
             do fc = 1,num_soilc
                c = filter_soilc(fc)
                this%totlit_1m(c) = &
                     this%totlit_1m(c) + &
                     this%decomp_pools_1m(c,l)
             end do
          endif
       end do

       ! total soil organic matter carbon in the top meter (TOTSOMC_1m)
       do fc = 1,num_soilc
          c = filter_soilc(fc)
          this%totsom_1m(c) = 0._r8
       end do
       do l = 1, ndecomp_pools
          if ( decomp_cascade_con%is_soil(l) ) then
             do fc = 1,num_soilc
                c = filter_soilc(fc)
                this%totsom_1m(c) = &
                     this%totsom_1m(c) + &
                     this%decomp_pools_1m(c,l)
             end do
          end if
       end do

    end if ! nlevdecomp>1

    ! total litter carbon (TOTLITC)
    do fc = 1,num_soilc
       c = filter_soilc(fc)
       this%totlit(c) = 0._r8
    end do
    do l = 1, ndecomp_pools
       if ( decomp_cascade_con%is_litter(l) ) then
          do fc = 1,num_soilc
             c = filter_soilc(fc)
             this%totlit(c) = &
                  this%totlit(c) + &
                  this%decomp_pools(c,l)
          end do
       endif
    end do

    ! total soil organic matter carbon (TOTSOMC)
    do fc = 1,num_soilc
       c = filter_soilc(fc)
       this%totsom(c) = 0._r8
    end do
    do l = 1, ndecomp_pools
       if ( decomp_cascade_con%is_soil(l) ) then
          do fc = 1,num_soilc
             c = filter_soilc(fc)
             this%totsom(c) = &
                  this%totsom(c) + &
                  this%decomp_pools(c,l)
          end do
       end if
    end do

    ! coarse woody debris carbon
    do fc = 1,num_soilc
       c = filter_soilc(fc)
       this%cwd(c) = 0._r8
    end do
    do l = 1, ndecomp_pools
       if ( decomp_cascade_con%is_cwd(l) ) then
          do fc = 1,num_soilc
             c = filter_soilc(fc)
             this%cwd(c) = &
                  this%cwd(c) + &
                  this%decomp_pools(c,l)
          end do
       end if
    end do

    ! truncation carbon
    do fc = 1,num_soilc
       c = filter_soilc(fc)
       this%trunc_sink(c) = 0._r8
    end do
    do j = 1, nlev
       do fc = 1,num_soilc
          c = filter_soilc(fc)
          this%trunc_sink(c) = &
               this%trunc_sink(c) + &
               this%trunc_sink_vr(c,j) * dzsoi_decomp(j)
       end do
    end do
  end subroutine column_nutrient_state_summary

  !-----------------------------------------------------------------------
  subroutine column_nutrient_state_setvalues(this, num_column, filter_column, value_column)
    !$acc routine seq
    !
    ! !ARGUMENTS:
    type(column_nutrient_state), intent(inout) :: this
    integer , intent(in) :: num_column
    integer , intent(in) :: filter_column(:)
    real(r8), intent(in) :: value_column
    integer :: fi,i     ! loop index
    integer :: j,k      ! indices
    !-----------------------------------------------------------------------
    !------------------------------------------------------------------------

    do fi = 1,num_column
       i = filter_column(fi)
       this%trunc_sink(i)      = value_column
       this%cwd(i)        = value_column
       this%totlit(i)     = value_column
       this%totsom(i)     = value_column
       this%totecosys(i)  = value_column
       this%totcol(i)     = value_column
       this%totsom_1m(i)  = value_column
       this%totlit_1m(i)  = value_column

    end do

    do j = 1,nlevdecomp_full
       do fi = 1,num_column
          i = filter_column(fi)
          this%trunc_sink_vr(i,j)      = value_column
       end do
    end do

    ! column and decomp_pools
    do k = 1, ndecomp_pools
       do fi = 1,num_column
          i = filter_column(fi)
          this%decomp_pools(i,k)    = value_column
          this%decomp_pools_1m(i,k) = value_column
       end do
    end do

    ! column levdecomp, and decomp_pools
    do j = 1,nlevdecomp_full
       do k = 1, ndecomp_pools
          do fi = 1,num_column
             i = filter_column(fi)
             this%decomp_pools_vr(i,j,k) = value_column
          end do
       end do
    end do

  end subroutine column_nutrient_state_setvalues

