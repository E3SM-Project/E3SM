                  xtype=ncd_double, dim1name='pft', long_name='pool for seeding new crop growth', &
                  units=nutrient_units(this%species, 'g#/m2'), interpinic_flag='interp', &
                  readvar=readvar, data=this%cropseed_deficit)

          end if
       end if
    end if

  end subroutine vegetation_nutrient_state_restart

  !-----------------------------------------------------------------------
  subroutine vegetation_nutrient_state_summary(this, num_soilp, filter_soilp)
    !
    ! !ARGUMENTS:
    type(vegetation_nutrient_state), intent(inout) :: this
    integer                   , intent(in)    :: num_soilp       ! number of soil patches in filter
    integer                   , intent(in)    :: filter_soilp(:) ! filter for soil patches
    integer :: p
    integer  :: fp              ! filter indices
    !-----------------------------------------------------------------------

    do fp = 1,num_soilp
       p = filter_soilp(fp)
       ! displayed vegetation carbon, excluding storage and cpool (DISPVEGC)
       this%dispveg(p) =        &
            this%leaf(p)      + &
            this%froot(p)     + &
            this%livestem(p)  + &
            this%deadstem(p)  + &
            this%livecroot(p) + &
            this%deadcroot(p)

       if ( crop_prog .and. iscft(veg_pp%itype(p)))then

          this%dispveg(p) =            &
               this%dispveg(p)       + &
               this%grain(p)
       end if
    end do ! filtered veg list

  end subroutine vegetation_nutrient_state_summary

  !-----------------------------------------------------------------------
  subroutine vegetation_nutrient_state_zerodwt(this, bounds)
    !
    ! !ARGUMENTS:
    type(vegetation_nutrient_state), intent(inout) :: this
    type(bounds_type), intent(in)  :: bounds
    integer  :: p          ! indices
    !-----------------------------------------------------------------------
    !-----------------------------------------------------------------------

    do p = bounds%begp,bounds%endp
       this%dispveg(p)   = 0._r8
       this%storveg(p)   = 0._r8
       this%totpft(p)    = 0._r8
    end do

  end subroutine vegetation_nutrient_state_zerodwt

