    allocate(this%manure                              (begp:endp)) ; this%manure                              (:) = spval
    allocate(this%nfertilization                      (begp:endp)) ; this%nfertilization                      (:) = spval
    allocate(this%fert_counter                        (begp:endp)) ; this%fert_counter                        (:) = spval
