  subroutine col_ps_setvalues ( this, num_column, filter_column, value_column)
    !
    ! !DESCRIPTION:
    ! Set phosphorus state variables, column-level
    !$acc routine seq
    ! !ARGUMENTS:
    class (column_phosphorus_state) :: this
    integer , intent(in)            :: num_column
    integer , intent(in)            :: filter_column(:)
    real(r8), intent(in)            :: value_column
    !
    ! !LOCAL VARIABLES:
    integer :: fi,i     ! loop index
    integer :: j,k      ! indices
    !------------------------------------------------------------------------
    call column_nutrient_state_setvalues(this%core, num_column, filter_column, value_column)
    do fi = 1,num_column
       i = filter_column(fi)

       this%mineral%smin(i)       = value_column
       this%solutionp(i)   = value_column
       this%labilep(i)     = value_column
       this%secondp(i)     = value_column
       this%occlp(i)       = value_column
       this%primp(i)       = value_column
    end do

    do j = 1,nlevdecomp_full
       do fi = 1,num_column
          i = filter_column(fi)
          this%mineral%smin_vr(i,j)       = value_column
          this%solutionp_vr(i,j)   = value_column
          this%labilep_vr(i,j)     = value_column
          this%secondp_vr(i,j)     = value_column
          this%occlp_vr(i,j)       = value_column
          this%primp_vr(i,j)       = value_column
       end do
    end do

  end subroutine col_ps_setvalues

  !-----------------------------------------------------------------------
  subroutine col_ps_summary(this, bounds, num_soilc, filter_soilc)
    !
    ! !ARGUMENTS:
    class (column_phosphorus_state) :: this
    type(bounds_type) , intent(in)  :: bounds
    integer           , intent(in)  :: num_soilc       ! number of soil columns in filter
    integer           , intent(in)  :: filter_soilc(:) ! filter for soil columns
    !
    ! !LOCAL VARIABLES:
    integer  :: c,j,k,l   ! indices
    integer  :: fc       ! lake filter indices
    real(r8) :: maxdepth    ! depth to integrate soil variables
    !-----------------------------------------------------------------------
   call column_nutrient_state_summary(this%core, num_soilc, filter_soilc)
   do fc = 1,num_soilc
      c = filter_soilc(fc)
      this%solutionp(c) =0._r8
      this%labilep(c)   =0._r8
      this%secondp(c)   =0._r8
      this%occlp(c)     =0._r8
      this%primp(c)     =0._r8
   end do

   do j = 1, nlevdecomp
      do fc = 1,num_soilc
         c = filter_soilc(fc)
         this%solutionp(c) = &
              this%solutionp(c) + &
              this%solutionp_vr(c,j) * dzsoi_decomp(j)
         this%labilep(c) = &
              this%labilep(c) + &
              this%labilep_vr(c,j) * dzsoi_decomp(j)
         this%secondp(c) = &
              this%secondp(c) + &
              this%secondp_vr(c,j) * dzsoi_decomp(j)
         this%occlp(c) = &
              this%occlp(c) + &
              this%occlp_vr(c,j) * dzsoi_decomp(j)
         this%primp(c) = &
              this%primp(c) + &
              this%primp_vr(c,j) * dzsoi_decomp(j)
      end do
   end do

   ! total sminp
   do fc = 1,num_soilc
      c = filter_soilc(fc)
      this%mineral%smin(c)      = 0._r8
   end do
   do j = 1, nlevdecomp
      do fc = 1,num_soilc
         c = filter_soilc(fc)
         this%mineral%smin_vr(c,j) = this%solutionp_vr(c,j) + &
                                  this%labilep_vr(c,j) + &
                                  this%secondp_vr(c,j)
      end do
   end do
   do j = 1, nlevdecomp
      do fc = 1,num_soilc
         c = filter_soilc(fc)
         this%mineral%smin(c) =  this%mineral%smin(c) + &
         this%mineral%smin_vr(c,j) * dzsoi_decomp(j)
      end do
   end do

   do fc = 1,num_soilc
      c = filter_soilc(fc)

      ! total wood product phosphorus
      this%core%totprod(c) = &
           this%core%prod1(c) + &
           this%core%prod10(c) + &
           this%core%prod100(c)

      ! total ecosystem phosphorus, including veg (TOTECOSYSP)
      this%core%totecosys(c) = &
           this%core%cwd(c) + &
           this%core%totlit(c) + &
           this%core%totsom(c) + &
           this%solutionp(c) + &
           this%labilep(c) + &
           this%secondp(c) + &
           this%primp(c) + &
           this%occlp(c) + &
           this%core%totprod(c) + &
           this%core%totveg(c)

      ! total column phosphorus, including pft (TOTCOLP)
      this%core%totcol(c) = &
           this%core%totpft(c) + &
           this%core%cwd(c) + &
           this%core%totlit(c) + &
           this%core%totsom(c) + &
           this%core%totprod(c) + &
           this%solutionp(c) + &
           this%labilep(c) + &
           this%secondp(c) + &
           this%core%trunc_sink(c)

       ! if we are using the crop model, then we need to add the cropseedc deficit
       if (use_crop) then 
          this%core%totcol(c) = this%core%totcol(c) + this%core%cropseed_deficit(c)
       endif 
   end do

  end subroutine col_ps_summary

  subroutine col_ps_zero_forfates_veg(this, bounds, num_soilc, filter_soilc)
    !
    ! !DESCRIPTION:
    ! As an alternative to summarizing vegetation states in CTC and then
    ! upscaling to the column level, we just zero them when FATES is turned on
    ! (or other potential models).
    !
    ! !ARGUMENTS:
    class(column_phosphorus_state) :: this
    type(bounds_type)      , intent(in)    :: bounds
    integer                , intent(in)    :: num_soilc       ! number of soil columns in filter
    integer                , intent(in)    :: filter_soilc(:) ! filter for soil columns
    ! locals
    integer :: fc
    integer :: c

    if(.not.use_fates) return

    do fc = 1,num_soilc
       c = filter_soilc(fc)
       this%core%totpft(c) = 0._r8
       this%core%totveg(c) = 0._r8
       this%core%cropseed_deficit(c) = 0._r8
    end do

    return
  end subroutine col_ps_zero_forfates_veg

