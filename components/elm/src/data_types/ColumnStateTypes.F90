       this%manure_r_app(begc:endc) = spval
       call hist_addfld1d (fname='MAN_R_APP', units='gN/m^2', &
            avgflag='A', long_name='Resistant manure nitrogen, application', &
            ptr_col=this%manure_r_app, default='inactive')

