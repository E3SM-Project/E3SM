    ! !ARGUMENTS:
    class(vegetation_nitrogen_state) :: this
    integer, intent(in)              :: begp,endp
    type(vegetation_carbon_state)    :: veg_cs ! used with C:N ratios on cold start
    !
    ! !LOCAL VARIABLES:
    integer :: fp,l,c,p                                 ! indices
    integer :: num_special_veg                          ! number of good values in special_patch filter
    integer :: special_veg (endp-begp+1)  ! special landunit filter - patches
    !------------------------------------------------------------------------

    !-----------------------------------------------------------------------
    ! allocate for each member of veg_ns
    !-----------------------------------------------------------------------
    this%core%species = CN_SPECIES_N
    call vegetation_nutrient_state_init(this%core, begp, endp)
    allocate(this%retrans%pool               (begp:endp))           ; this%retrans%pool            (:)   = spval
    allocate(this%plant_n_buffer         (begp:endp))           ; this%plant_n_buffer      (:)   = spval
    allocate(this%npimbalance            (begp:endp))           ; this%npimbalance         (:)   = spval
    allocate(this%pnup_pfrootc           (begp:endp))           ; this%pnup_pfrootc        (:)   = spval
    allocate(this%ppup_pfrootc           (begp:endp))           ; this%ppup_pfrootc        (:)   = spval
    allocate(this%ptlai_pleafc           (begp:endp))           ; this%ptlai_pleafc        (:)   = spval
    allocate(this%ppsnsun_ptlai          (begp:endp))           ; this%ppsnsun_ptlai       (:)   = spval
    allocate(this%ppsnsun_pleafn         (begp:endp))           ; this%ppsnsun_pleafn      (:)   = spval
    allocate(this%ppsnsun_pleafp         (begp:endp))           ; this%ppsnsun_pleafp      (:)   = spval
    allocate(this%plmrsun_ptlai          (begp:endp))           ; this%plmrsun_ptlai       (:)   = spval
    allocate(this%plmrsun_pleafn         (begp:endp))           ; this%plmrsun_pleafn      (:)   = spval
    allocate(this%plaisun_ptlai          (begp:endp))           ; this%plaisun_ptlai       (:)   = spval
    allocate(this%ppsnsha_ptlai          (begp:endp))           ; this%ppsnsha_ptlai       (:)   = spval
    allocate(this%ppsnsha_pleafn         (begp:endp))           ; this%ppsnsha_pleafn      (:)   = spval
    allocate(this%ppsnsha_pleafp         (begp:endp))           ; this%ppsnsha_pleafp      (:)   = spval
    allocate(this%plmrsha_ptlai          (begp:endp))           ; this%plmrsha_ptlai       (:)   = spval
    allocate(this%plmrsha_pleafn         (begp:endp))           ; this%plmrsha_pleafn      (:)   = spval
    allocate(this%plaisha_ptlai          (begp:endp))           ; this%plaisha_ptlai       (:)   = spval
    allocate(this%benefit_pgpp_pleafc    (begp:endp))           ; this%benefit_pgpp_pleafc (:)   = spval
    allocate(this%benefit_pgpp_pleafn    (begp:endp))           ; this%benefit_pgpp_pleafn (:)   = spval
    allocate(this%benefit_pgpp_pleafp    (begp:endp))           ; this%benefit_pgpp_pleafp (:)   = spval
    allocate(this%cost_pgpp_pfrootc      (begp:endp))           ; this%cost_pgpp_pfrootc   (:)   = spval
    allocate(this%cost_plmr_pleafc       (begp:endp))           ; this%cost_plmr_pleafc    (:)   = spval
    allocate(this%cost_plmr_pleafn       (begp:endp))           ; this%cost_plmr_pleafn    (:)   = spval
    allocate(this%ppsn_ptlai_z           (begp:endp,1:nlevcan)) ; this%ppsn_ptlai_z        (:,:) = spval
    allocate(this%ppsn_pleafn_z          (begp:endp,1:nlevcan)) ; this%ppsn_pleafn_z       (:,:) = spval
    allocate(this%ppsn_pleafp_z          (begp:endp,1:nlevcan)) ; this%ppsn_pleafp_z       (:,:) = spval
    allocate(this%ppsn_ptlai_z_vcmax     (begp:endp,1:nlevcan)) ; this%ppsn_ptlai_z_vcmax  (:,:) = spval
    allocate(this%ppsn_pleafn_z_vcmax    (begp:endp,1:nlevcan)) ; this%ppsn_pleafn_z_vcmax (:,:) = spval
    allocate(this%ppsn_pleafp_z_vcmax    (begp:endp,1:nlevcan)) ; this%ppsn_pleafp_z_vcmax (:,:) = spval
    allocate(this%ppsn_ptlai_z_jmax      (begp:endp,1:nlevcan)) ; this%ppsn_ptlai_z_jmax   (:,:) = spval
    allocate(this%ppsn_pleafn_z_jmax     (begp:endp,1:nlevcan)) ; this%ppsn_pleafn_z_jmax  (:,:) = spval
    allocate(this%ppsn_pleafp_z_jmax     (begp:endp,1:nlevcan)) ; this%ppsn_pleafp_z_jmax  (:,:) = spval
    allocate(this%ppsn_ptlai_z_tpu       (begp:endp,1:nlevcan)) ; this%ppsn_ptlai_z_tpu    (:,:) = spval
    allocate(this%ppsn_pleafn_z_tpu      (begp:endp,1:nlevcan)) ; this%ppsn_pleafn_z_tpu   (:,:) = spval
    allocate(this%ppsn_pleafp_z_tpu      (begp:endp,1:nlevcan)) ; this%ppsn_pleafp_z_tpu   (:,:) = spval
    allocate(this%plmr_ptlai_z           (begp:endp,1:nlevcan)) ; this%plmr_ptlai_z        (:,:) = spval
    allocate(this%plmr_pleafn_z          (begp:endp,1:nlevcan)) ; this%plmr_pleafn_z       (:,:) = spval

    !-----------------------------------------------------------------------
    ! initialize history fields for select members of veg_ns
    !-----------------------------------------------------------------------
    if (crop_prog) then
       this%core%grain(begp:endp) = spval
       call hist_addfld1d (fname='GRAINN', units='gN/m^2', &
            avgflag='A', long_name='grain N', &
            ptr_patch=this%core%grain, default='inactive')

       this%core%cropseed_deficit(begp:endp) = spval
       call hist_addfld1d (fname='CROPSEEDN_DEFICIT', units='gN/m^2', &
            avgflag='A', long_name='N used for crop seed that needs to be repaid', &
            ptr_patch=this%core%cropseed_deficit)
    end if
    call vegetation_nutrient_state_init_history(this%core, begp, endp)

    this%retrans%pool(begp:endp) = spval
    call hist_addfld1d (fname='RETRANSN', units='gN/m^2', &
         avgflag='A', long_name='plant pool of retranslocated N', &
         ptr_patch=this%retrans%pool)

    this%npimbalance(begp:endp) = spval
    call hist_addfld1d (fname='leaf_npimbalance', units='gN/gP', &
         avgflag='A', long_name='leaf np imbalance partial C partial P/partial C partial N', &
         ptr_patch=this%npimbalance)

    ! Note: this is a patch-level variable, reported to the column-level
    this%plant_n_buffer(begp:endp) = spval
    call hist_addfld1d (fname='PLANTN_BUFFER', units='gN/m^2', &
         avgflag='A', long_name='plant nitrogen stored as buffer', &
         ptr_col=this%plant_n_buffer,default='inactive')

    !-----------------------------------------------------------------------
    ! set cold-start initial values for select members of veg_ns
    !-----------------------------------------------------------------------

    do p = begp,endp

       l = veg_pp%landunit(p)
       if (veg_pp%is_on_soil_col(p) .or. veg_pp%is_on_crop_col(p)) then
          if (veg_pp%itype(p) == noveg) then
             this%core%leaf(p) = 0._r8
             this%core%leaf_storage(p) = 0._r8
          else
             this%core%leaf(p)         = veg_cs%core%leaf(p)         / veg_vp%leafcn(veg_pp%itype(p))
             this%core%leaf_storage(p) = veg_cs%core%leaf_storage(p) / veg_vp%leafcn(veg_pp%itype(p))
          end if

          this%core%leaf_xfer(p)        = 0._r8
          if ( crop_prog )then
             this%core%grain(p)            = 0._r8
             this%core%grain_storage(p)    = 0._r8
             this%core%grain_xfer(p)       = 0._r8
          end if
          this%core%cropseed_deficit(p) = 0._r8
          this%core%froot(p)            = 0._r8
          this%core%froot_storage(p)    = 0._r8
          this%core%froot_xfer(p)       = 0._r8
          this%core%livestem(p)         = 0._r8
          this%core%livestem_storage(p) = 0._r8
          this%core%livestem_xfer(p)    = 0._r8

          ! tree types need to be initialized with some stem mass so that
          ! roughness length is not zero in canopy flux calculation

          if (veg_vp%woody(veg_pp%itype(p)) >= 1.0_r8) then
             this%core%deadstem(p) = veg_cs%core%deadstem(p) / veg_vp%deadwdcn(veg_pp%itype(p))
          else
             this%core%deadstem(p) = 0._r8
          end if

          if (nu_com .ne. 'RD') then
              ! ECA competition calculate root NP uptake as a function of fine root biomass
              ! better to initialize root CNP pools with a non-zero value
              if (veg_pp%itype(p) .ne. noveg) then
                 this%core%froot(p) = veg_cs%core%froot(p) / veg_vp%frootcn(veg_pp%itype(p))
                 this%core%froot_storage(p) = veg_cs%core%froot_storage(p) / veg_vp%frootcn(veg_pp%itype(p))
              end if
          end if

          this%core%deadstem_storage(p)  = 0._r8
          this%core%deadstem_xfer(p)     = 0._r8
          this%core%livecroot(p)         = 0._r8
          this%core%livecroot_storage(p) = 0._r8
          this%core%livecroot_xfer(p)    = 0._r8
          this%core%deadcroot(p)         = 0._r8
          this%core%deadcroot_storage(p) = 0._r8
          this%core%deadcroot_xfer(p)    = 0._r8
          this%retrans%pool(p)           = 0._r8
          this%core%pool(p)              = 0._r8
          if (nstor(veg_pp%itype(p)) .gt. 1e-6_r8) then
              this%core%pool(p)          = 10.0_r8
          end if
          this%core%trunc_sink(p)             = 0._r8
          this%core%dispveg(p)           = 0._r8
          this%core%storveg(p)           = 0._r8
          this%core%totveg(p)            = 0._r8
          this%core%totpft(p)            = 0._r8
          this%plant_n_buffer(p)     = 1._r8
       end if

       this%npimbalance(p) = 0.0_r8
       this%pnup_pfrootc(p) = 0.0_r8
       this%benefit_pgpp_pleafc(p) = 0.0_r8
    end do

    ! Set filter for special landunits, set values
    num_special_veg = 0
    do p = begp,endp
       l = veg_pp%landunit(p)
       if (lun_pp%ifspecial(l)) then
          num_special_veg = num_special_veg + 1
          special_veg(num_special_veg) = p
       end if
    end do
    call this%SetValues (num_veg=num_special_veg, filter_veg=special_veg, value_veg=0._r8)

  end subroutine veg_ns_init

  !-----------------------------------------------------------------------
  subroutine veg_ns_restart ( this,  bounds, ncid, flag)
    !
    ! !DESCRIPTION:
    ! Read/write CN restart data for vegetation nitrogen state variables
    !
    ! !ARGUMENTS:
    class (vegetation_nitrogen_state)          :: this
    type(bounds_type)          , intent(in)    :: bounds
    type(file_desc_t)          , intent(inout) :: ncid
    character(len=*)           , intent(in)    :: flag   !'read' or 'write' or 'define'
    !
    ! !LOCAL VARIABLES:
    integer            :: i
    logical            :: readvar
    integer            :: idata
    logical            :: exit_spinup = .false.
    logical            :: enter_spinup = .false.
    real(r8)           :: m_veg          ! multiplier for the exit_spinup code
    character(len=128) :: varname    ! temporary
    ! spinup state as read from restart file, for determining whether to enter or exit spinup mode.
    integer            :: restart_file_spinup_state
    call vegetation_nutrient_state_restart(this%core, ncid, flag)

    call restartvar(ncid=ncid, flag=flag, varname='retransn', xtype=ncd_double,  &
         dim1name='pft', long_name='', units='', &
         interpinic_flag='interp', readvar=readvar, data=this%retrans%pool)

    call restartvar(ncid=ncid, flag=flag,  varname='npimbalance_patch', xtype=ncd_double,  &
        dim1name='pft',    long_name='npimbalance_patch', units='-', &
        interpinic_flag='interp', readvar=readvar, data=this%npimbalance)
     call restartvar(ncid=ncid, flag=flag,  varname='pnup_pfrootc_patch', xtype=ncd_double,  &
        dim1name='pft',    long_name='pnup_pfrootc_patch', units='-', &
        interpinic_flag='interp', readvar=readvar, data=this%pnup_pfrootc)
    call restartvar(ncid=ncid, flag=flag,  varname='benefit_pgpp_pleafc_patch', xtype=ncd_double,  &
        dim1name='pft',    long_name='benefit_pgpp_pleafc_patch', units='-', &
        interpinic_flag='interp', readvar=readvar, data=this%benefit_pgpp_pleafc)

    !--------------------------------
    ! Spinup state operations happen on restart write/read
    !--------------------------------
    ! the spinup_state variable is being written by the column-level carbon state restart
    ! routine, so only need to handle the reading part here
     if (flag == 'read') then
        call restartvar(ncid=ncid, flag=flag, varname='spinup_state', xtype=ncd_int,  &
             long_name='Spinup state of the model that wrote this restart file: ' &
             // ' 0 = normal model mode, 1 = AD spinup', units='', &
             interpinic_flag='copy', readvar=readvar,  data=idata)
        if (readvar) then
           restart_file_spinup_state = idata
        else
           ! assume, for sake of backwards compatibility, that if spinup_state is not in
           ! the restart file then current model state is the same as prior model state
           restart_file_spinup_state = spinup_state
           if ( masterproc ) then
              write(iulog,*) ' CNRest: WARNING!  Restart file does not contain info ' &
                   // ' on spinup state used to generate the restart file. '
              write(iulog,*) '   Assuming the same as current setting: ', spinup_state
           end if
        end if
     end if ! read

     ! now compare the model and restart file spinup states, and either take the
     ! model into spinup mode or out of it if they are not identical.
     ! taking model out of spinup mode requires multiplying each pool
     ! by the associated AD factor.
     ! putting model into spinup mode requires dividing each pool
     ! by the associated AD factor.
     ! only allow this to occur on first timestep of model run.

     if (flag == 'read' .and. spinup_state /= restart_file_spinup_state ) then
        if (spinup_state == 0 .and. restart_file_spinup_state == 1 ) then
           if ( masterproc ) write(iulog,*) ' veg_cs_restart: taking deadwood pools out of AD spinup mode'
           exit_spinup = .true.
        else if (spinup_state == 1 .and. restart_file_spinup_state == 0 ) then
           if ( masterproc ) write(iulog,*) ' veg_cs_restart: taking deadwood pools into AD spinup mode'
           enter_spinup = .true.
        else
           call endrun(msg=' veg_ns_restart: error in entering/exiting spinup.  spinup_state ' &
                // ' != restart_file_spinup_state, but do not know what to do'//&
                errMsg(__FILE__, __LINE__))
        end if
        if (get_nstep() >= 2) then
           call endrun(msg=' veg_ns_restart: error in entering/exiting spinup - should occur only when nstep = 1'//&
                errMsg(__FILE__, __LINE__))
        endif
        do i = bounds%begp, bounds%endp
           if (exit_spinup) then
              m_veg = spinup_mortality_factor
           else if (enter_spinup) then
              m_veg = 1._r8 / spinup_mortality_factor
           end if
           this%core%deadstem(i)  = this%core%deadstem(i) * m_veg
           this%core%deadcroot(i) = this%core%deadcroot(i) * m_veg
        end do
     end if ! read

  end subroutine veg_ns_restart

  !-----------------------------------------------------------------------
  subroutine veg_ns_summary(this, bounds, num_soilc, filter_soilc, num_soilp, filter_soilp, col_ns)
    !
    ! !DESCRIPTION:
    ! Vegetation-level nitrogen state summary calculations
    !
    ! !ARGUMENTS:
    class(vegetation_nitrogen_state)            :: this
    type(bounds_type)           , intent(in)    :: bounds
    integer                     , intent(in)    :: num_soilc       ! number of soil columns in filter
    integer                     , intent(in)    :: filter_soilc(:) ! filter for soil columns
    integer                     , intent(in)    :: num_soilp       ! number of soil patches in filter
    integer                     , intent(in)    :: filter_soilp(:) ! filter for soil patches
    type (column_nitrogen_state), intent(inout) :: col_ns          ! column-level nitrogen state for p2c

    !
    ! !LOCAL VARIABLES:
    integer  :: c,p             ! indices
    integer  :: fp              ! filter indices
    !-----------------------------------------------------------------------
    call vegetation_nutrient_state_summary(this%core, num_soilp, filter_soilp)
    associate( &
     plant_n_buffer_patch  => this%plant_n_buffer  , &
     plant_n_buffer_col    => col_ns%plant_n_buffer , &
     totvegn_patch  => this%core%totveg   , &
     totvegn_col    => col_ns%core%totveg, &
     totpftn_patch  => this%core%totpft   , &
     totpftn_col    => col_ns%core%totpft, &
     cropseedn_deficit_patch  => this%core%cropseed_deficit , &
     cropseedn_deficit_col    => col_ns%core%cropseed_deficit &
      )

    do fp = 1,num_soilp
       p = filter_soilp(fp)

      ! stored vegetation nitrogen, including retranslocated N pool (STORVEGN)
      this%core%storveg(p) = &
           this%core%leaf_storage(p)      + &
           this%core%froot_storage(p)     + &
           this%core%livestem_storage(p)  + &
           this%core%deadstem_storage(p)  + &
           this%core%livecroot_storage(p) + &
           this%core%deadcroot_storage(p) + &
           this%core%leaf_xfer(p)         + &
           this%core%froot_xfer(p)        + &
           this%core%livestem_xfer(p)     + &
           this%core%deadstem_xfer(p)     + &
           this%core%livecroot_xfer(p)    + &
           this%core%deadcroot_xfer(p)    + &
           this%core%pool(p)              + &
           this%retrans%pool(p)

      if ( crop_prog .and. iscft(veg_pp%itype(p)))then

         this%core%storveg(p) = &
              this%core%storveg(p) + &
              this%core%grain_storage(p)     + &
              this%core%grain_xfer(p)
      end if

      ! total vegetation nitrogen (TOTVEGN)
      this%core%totveg(p) = &
           this%core%dispveg(p) + &
           this%core%storveg(p)

      ! total pft-level carbon (add pft_ntrunc)
      this%core%totpft(p) = &
           this%core%totveg(p) + &
           this%core%trunc_sink(p)
   end do ! filtered veg loop

   call p2c(bounds, num_soilc, filter_soilc, &
        plant_n_buffer_patch(bounds%begp:bounds%endp)  , &
        plant_n_buffer_col(bounds%begc:bounds%endc))

   call p2c(bounds, num_soilc, filter_soilc, &
        totvegn_patch(bounds%begp:bounds%endp) , &
        totvegn_col(bounds%begc:bounds%endc))

   call p2c(bounds, num_soilc, filter_soilc, &
        totpftn_patch(bounds%begp:bounds%endp) , &
        totpftn_col(bounds%begc:bounds%endc))

   if (use_crop) then
      call p2c(bounds, num_soilc, filter_soilc, &
           cropseedn_deficit_patch(bounds%begp:bounds%endp) , &
           cropseedn_deficit_col(bounds%begc:bounds%endc))
   endif
   end associate

  end subroutine veg_ns_summary

  !-----------------------------------------------------------------------
  subroutine veg_ns_setvalues ( this, num_veg, filter_veg, value_veg)
    !
    ! !DESCRIPTION:
    ! Set nitrogen state variables
    !
    ! !ARGUMENTS:
    class (vegetation_nitrogen_state) :: this
    integer , intent(in) :: num_veg
    integer , intent(in) :: filter_veg(:)
    real(r8), intent(in) :: value_veg
    !
    ! !LOCAL VARIABLES:
    integer :: fi,i     ! loop index
    !------------------------------------------------------------------------

    do fi = 1,num_veg
       i = filter_veg(fi)

       this%core%leaf(i)              = value_veg
       this%core%leaf_storage(i)      = value_veg
       this%core%leaf_xfer(i)         = value_veg
       this%core%froot(i)             = value_veg
       this%core%froot_storage(i)     = value_veg
       this%core%froot_xfer(i)        = value_veg
       this%core%livestem(i)          = value_veg
       this%core%livestem_storage(i)  = value_veg
       this%core%livestem_xfer(i)     = value_veg
       this%core%deadstem(i)          = value_veg
       this%core%deadstem_storage(i)  = value_veg
       this%core%deadstem_xfer(i)     = value_veg
       this%core%livecroot(i)         = value_veg
       this%core%livecroot_storage(i) = value_veg
       this%core%livecroot_xfer(i)    = value_veg
       this%core%deadcroot(i)         = value_veg
       this%core%deadcroot_storage(i) = value_veg
       this%core%deadcroot_xfer(i)    = value_veg
       this%retrans%pool(i)           = value_veg
       this%core%pool(i)              = value_veg
       this%core%trunc_sink(i)             = value_veg
       this%core%dispveg(i)           = value_veg
       this%core%storveg(i)           = value_veg
       this%core%totveg(i)            = value_veg
       this%core%totpft(i)            = value_veg
    end do

    if ( crop_prog )then
       do fi = 1,num_veg
          i = filter_veg(fi)
          this%core%grain(i)            = value_veg
          this%core%grain_storage(i)    = value_veg
          this%core%grain_xfer(i)       = value_veg
          this%core%cropseed_deficit(i) = value_veg
       end do
    end if

  end subroutine veg_ns_setvalues

