  !-----------------------------------------------------------------------
  subroutine veg_ps_summary (this, bounds, num_soilc, filter_soilc, num_soilp, filter_soilp, col_ps)
    !
    ! !ARGUMENTS:
    class (vegetation_phosphorus_state) :: this
    type(bounds_type) , intent(in)      :: bounds
    integer           , intent(in)      :: num_soilc       ! number of soil columns in filter
    integer           , intent(in)      :: filter_soilc(:) ! filter for soil columns
    integer           , intent(in)      :: num_soilp       ! number of soil patches in filter
    integer           , intent(in)      :: filter_soilp(:) ! filter for soil patches
    type(column_phosphorus_state), intent(inout) :: col_ps
    !
    ! !LOCAL VARIABLES:
    integer  :: p        ! indices
    integer  :: fp       ! lake filter indices
    !-----------------------------------------------------------------------
    call vegetation_nutrient_state_summary(this%core, num_soilp, filter_soilp)
    associate( &
     totvegp_patch  => this%core%totveg   , &
     totvegp_col    => col_ps%core%totveg, &
     totpftp_patch  => this%core%totpft   , &
     totpftp_col    => col_ps%core%totpft, &
     cropseedp_deficit_patch  => this%core%cropseed_deficit , &
     cropseedp_deficit_col    => col_ps%core%cropseed_deficit &
      )
    do fp = 1,num_soilp
       p = filter_soilp(fp)

      ! stored vegetation phosphorus, including retranslocated N pool (STORVEGN)
      this%core%storveg(p) = &
           this%core%leaf_storage(p)      + &
           this%core%froot_storage(p)     + &
           this%core%livestem_storage(p)  + &
           this%core%deadstem_storage(p)  + &
           this%core%livecroot_storage(p) + &
           this%core%deadcroot_storage(p) + &
           this%core%leaf_xfer(p)         + &
           this%core%froot_xfer(p)        + &
           this%core%livestem_xfer(p)     + &
           this%core%deadstem_xfer(p)     + &
           this%core%livecroot_xfer(p)    + &
           this%core%deadcroot_xfer(p)    + &
           this%core%pool(p)              + &
           this%retrans%pool(p)

      if ( crop_prog .and. iscft(veg_pp%itype(p)))then

         this%core%storveg(p) = &
              this%core%storveg(p) + &
              this%core%grain_storage(p)     + &
              this%core%grain_xfer(p)
      end if

      ! total vegetation phosphorus (TOTVEGN)
      this%core%totveg(p) = &
           this%core%dispveg(p) + &
           this%core%storveg(p)

      ! total pft-level carbon (add pft_ntrunc)
      this%core%totpft(p) = &
           this%core%totveg(p) + &
           this%core%trunc_sink(p)

   end do

   call p2c(bounds, num_soilc, filter_soilc, &
        totvegp_patch(bounds%begp:bounds%endp)  , &
        totvegp_col(bounds%begc:bounds%endc) )

   call p2c(bounds, num_soilc, filter_soilc, &
        totpftp_patch(bounds%begp:bounds%endp) , &
        totpftp_col(bounds%begc:bounds%endc) )

   if (use_crop) then
      call p2c(bounds, num_soilc, filter_soilc, &
           cropseedp_deficit_patch(bounds%begp:bounds%endp) , &
           cropseedp_deficit_col(bounds%begc:bounds%endc) )
   endif
   end associate

  end subroutine veg_ps_summary

