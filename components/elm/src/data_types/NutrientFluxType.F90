  end subroutine vegetation_nutrient_flux_init_history

  !-----------------------------------------------------------------------
  subroutine vegetation_nutrient_flux_restart(this, ncid, flag)
    !
    ! !DESCRIPTION:
    ! Restart fields of the core of vegetation_carbon_flux, vegetation_nitrogen_flux, vegetation_phosphorus_flux:
    ! one restartvar per field for every species (generated by `spel nutrient restart`)
    !
    ! !ARGUMENTS:
    type(vegetation_nutrient_flux), intent(inout) :: this
    type(file_desc_t) , intent(inout) :: ncid   ! netcdf id
    character(len=*)  , intent(in)    :: flag   !'read' or 'write'
    logical :: readvar      ! determine if variable is on initial file
    !-----------------------------------------------------------------------

    if (crop_prog) then
       call restartvar (ncid=ncid, flag=flag, &
            varname=by_species(this%species, 'grainc_xfer_to_grainc', 'grainc_xfer_to_grainc', 'grainc_xfer_to_grainc', 'grainn_xfer_to_grainn', 'grainp_xfer_to_grainp'), &
            xtype=ncd_double, dim1name='pft', &
            long_name=by_species(this%species, 'grain C growth from storage', 'grain C growth from storage', 'grain C growth from storage', 'grain N growth from storage', 'grain P growth from storage'), &
            units=by_species(this%species, 'gC/m2/s', 'gC/m2/s', 'gC/m2/s', 'gN/m2/s', 'gP/m2/s'), &
            interpinic_flag='interp', readvar=readvar, data=this%grain_xfer_to_grain)

       call restartvar (ncid=ncid, flag=flag, &
            varname=by_species(this%species, 'livestemc_to_litter', 'livestemc_to_litter', 'livestemc_to_litter', 'livestemn_to_litter', 'livestemp_to_litter'), &
            xtype=ncd_double, dim1name='pft', &
            long_name=by_species(this%species, 'live stem C litterfall', 'live stem C litterfall', 'live stem C litterfall', 'livestem N to litter', 'livestem P to litter'), &
            units=by_species(this%species, 'gC/m2/s', 'gC/m2/s', 'gC/m2/s', 'gN/m2/s', 'gP/m2/s'), &
            interpinic_flag='interp', readvar=readvar, data=this%livestem_to_litter)

       call restartvar (ncid=ncid, flag=flag, &
            varname=by_species(this%species, 'grainc_to_food', 'grainc_to_food', 'grainc_to_food', 'grainn_to_food', 'grainp_to_food'), &
            xtype=ncd_double, dim1name='pft', &
            long_name=by_species(this%species, 'grain C to food', 'grain C to food', 'grain C to food', 'grain N to food', 'grain P to food'), &
            units=by_species(this%species, 'gC/m2/s', 'gC/m2/s', 'gC/m2/s', 'gN/m2/s', 'gP/m2/s'), &
            interpinic_flag='interp', readvar=readvar, data=this%grain_to_food)

       call restartvar (ncid=ncid, flag=flag, &
            varname=by_species(this%species, 'cpool_to_grainc', 'cpool_to_grainc', 'cpool_to_grainc', 'npool_to_grainn', 'ppool_to_grainp'), &
            xtype=ncd_double, dim1name='pft', &
            long_name=by_species(this%species, 'allocation to grain C', 'allocation to grain C', 'allocation to grain C', 'allocation to grain N', 'allocation to grain P'), &
            units=by_species(this%species, 'gC/m2/s', 'gC/m2/s', 'gC/m2/s', 'gN/m2/s', 'gP/m2/s'), &
            interpinic_flag='interp', readvar=readvar, data=this%pool_to_grain)

       call restartvar (ncid=ncid, flag=flag, &
            varname=by_species(this%species, 'cpool_to_grainc_storage', 'cpool_to_grainc_storage', 'cpool_to_grainc_storage', 'npool_to_grainn_storage', 'ppool_to_grainp_storage'), &
            xtype=ncd_double, dim1name='pft', &
            long_name=by_species(this%species, 'allocation to grain C storage', 'allocation to grain C storage', 'allocation to grain C storage', 'allocation to grain N storage', 'allocation to grain P storage'), &
            units=by_species(this%species, 'gC/m2/s', 'gC/m2/s', 'gC/m2/s', 'gN/m2/s', 'gP/m2/s'), &
            interpinic_flag='interp', readvar=readvar, data=this%pool_to_grain_storage)

       call restartvar (ncid=ncid, flag=flag, &
            varname=by_species(this%species, 'grainc_storage_to_xfer', 'grainc_storage_to_xfer', 'grainc_storage_to_xfer', 'grainn_storage_to_xfer', 'grainp_storage_to_xfer'), &
            xtype=ncd_double, dim1name='pft', &
            long_name=by_species(this%species, 'grain C shift storage to transfer', 'grain C shift storage to transfer', 'grain C shift storage to transfer', 'grain N shift storage to transfer', 'grain P shift storage to transfer'), &
            units=by_species(this%species, 'gC/m2/s', 'gC/m2/s', 'gC/m2/s', 'gN/m2/s', 'gP/m2/s'), &
            interpinic_flag='interp', readvar=readvar, data=this%grain_storage_to_xfer)

    end if
    call restartvar (ncid=ncid, flag=flag, &
         varname=by_species(this%species, 'plant_calloc', 'plant_calloc', 'plant_calloc', 'plant_nalloc', 'plant_palloc'), &
         xtype=ncd_double, dim1name='pft', long_name='', units='', interpinic_flag='interp', &
         readvar=readvar, data=this%plant_alloc)

    if (is_carbon(this%species)) then
       call restartvar (ncid=ncid, flag=flag, varname='prev_leafc_to_litter', xtype=ncd_double, &
            dim1name='pft', long_name='', units='', interpinic_flag='interp', readvar=readvar, &
            data=this%prev_leaf_to_litter)

       call restartvar (ncid=ncid, flag=flag, varname='prev_frootc_to_litter', xtype=ncd_double, &
            dim1name='pft', long_name='', units='', interpinic_flag='interp', readvar=readvar, &
            data=this%prev_froot_to_litter)

    end if

  end subroutine vegetation_nutrient_flux_restart

  !-----------------------------------------------------------------------
  subroutine vegetation_nutrient_flux_summary(this, num_soilp, filter_soilp)
    !
    ! !ARGUMENTS:
    type(vegetation_nutrient_flux), intent(inout) :: this
    integer                , intent(in)    :: num_soilp       ! number of soil patches in filter
    integer                , intent(in)    :: filter_soilp(:) ! filter for soil patches
    integer :: p
    integer  :: fp            ! lake filter indices
    !-----------------------------------------------------------------------

    ! patch loop
    do fp = 1,num_soilp
       p = filter_soilp(fp)

       ! patch-level wood harvest
       this%wood_harvest(p) = &
            this%hrv_deadstem_to_prod10(p) + &
            this%hrv_deadstem_to_prod100(p)
       if ( crop_prog .and. iscft(veg_pp%itype(p)))then
          this%wood_harvest(p) = &
               this%wood_harvest(p) + &
               this%hrv_crop_to_prod1(p)
       end if
    end do  ! end of patches loop

  end subroutine vegetation_nutrient_flux_summary

  !-----------------------------------------------------------------------
  subroutine vegetation_nutrient_flux_setvalues(this, num_patch, filter_patch, value_patch)
    !
    ! !ARGUMENTS:
    type(vegetation_nutrient_flux), intent(inout) :: this
    integer , intent(in) :: num_patch
    integer , intent(in) :: filter_patch(:)
    real(r8), intent(in) :: value_patch
    integer :: fi,i     ! loop index
    !-----------------------------------------------------------------------
    !------------------------------------------------------------------------

    if (.not. (is_carbon(this%species) .and. use_fates)) then
       do fi = 1,num_patch
          i = filter_patch(fi)

          this%leaf_xfer_to_leaf(i)                 = value_patch
          this%froot_xfer_to_froot(i)               = value_patch
          this%livestem_xfer_to_livestem(i)         = value_patch
          this%deadstem_xfer_to_deadstem(i)         = value_patch
          this%livecroot_xfer_to_livecroot(i)       = value_patch
          this%deadcroot_xfer_to_deadcroot(i)       = value_patch
          this%leaf_to_litter(i)                     = value_patch
          this%froot_to_litter(i)                    = value_patch
          this%pool_to_leaf(i)                      = value_patch
          this%pool_to_leaf_storage(i)              = value_patch
          this%pool_to_froot(i)                     = value_patch
          this%pool_to_froot_storage(i)             = value_patch
          this%pool_to_livestem(i)                  = value_patch
          this%pool_to_livestem_storage(i)          = value_patch
          this%pool_to_deadstem(i)                  = value_patch
          this%pool_to_deadstem_storage(i)          = value_patch
          this%pool_to_livecroot(i)                 = value_patch
          this%pool_to_livecroot_storage(i)         = value_patch
          this%pool_to_deadcroot(i)                 = value_patch
          this%pool_to_deadcroot_storage(i)         = value_patch
          
          this%leaf_storage_to_xfer(i)               = value_patch
          this%froot_storage_to_xfer(i)              = value_patch
          this%livestem_storage_to_xfer(i)           = value_patch
          this%deadstem_storage_to_xfer(i)           = value_patch
          this%livecroot_storage_to_xfer(i)          = value_patch
          this%deadcroot_storage_to_xfer(i)          = value_patch
          this%livestem_to_deadstem(i)              = value_patch
          this%livecroot_to_deadcroot(i)            = value_patch
          this%wood_harvest(i)                       = value_patch
          this%fire_loss(i)                          = value_patch
       end do
    end if !(.not.use_fates)

    if ( crop_prog )then
       do fi = 1,num_patch
          i = filter_patch(fi)
          this%grain_to_food(i)          = value_patch
          this%grain_xfer_to_grain(i)   = value_patch
          this%pool_to_grain(i)         = value_patch
          this%pool_to_grain_storage(i) = value_patch
          this%grain_storage_to_xfer(i)  = value_patch
       end do
    end if

    do fi = 1,num_patch
       i = filter_patch(fi)
       this%hrv_leaf_to_litter(i)                 = value_patch
       this%hrv_leaf_storage_to_litter(i)         = value_patch
       this%hrv_leaf_xfer_to_litter(i)            = value_patch
       this%hrv_froot_to_litter(i)                = value_patch
       this%hrv_froot_storage_to_litter(i)        = value_patch
       this%hrv_froot_xfer_to_litter(i)           = value_patch
       this%hrv_livestem_to_litter(i)             = value_patch
       this%hrv_livestem_storage_to_litter(i)     = value_patch
       this%hrv_livestem_xfer_to_litter(i)        = value_patch
       this%hrv_deadstem_to_prod10(i)            = value_patch
       this%hrv_deadstem_to_prod100(i)           = value_patch
       this%hrv_leaf_to_prod1(i)                 = value_patch
       this%hrv_livestem_to_prod1(i)             = value_patch
       this%hrv_grain_to_prod1(i)                = value_patch
       this%hrv_crop_to_prod1(i)                 = value_patch
       this%hrv_deadstem_storage_to_litter(i)     = value_patch
       this%hrv_deadstem_xfer_to_litter(i)        = value_patch
       this%hrv_livecroot_to_litter(i)            = value_patch
       this%hrv_livecroot_storage_to_litter(i)    = value_patch
       this%hrv_livecroot_xfer_to_litter(i)       = value_patch
       this%hrv_deadcroot_to_litter(i)            = value_patch
       this%hrv_deadcroot_storage_to_litter(i)    = value_patch
       this%hrv_deadcroot_xfer_to_litter(i)       = value_patch
       this%hrv_pool_to_litter(i)                 = value_patch
    end do 
  end subroutine vegetation_nutrient_flux_setvalues

  !-----------------------------------------------------------------------
  subroutine gridcell_nutrient_flux_zerodwt(this, bounds)
    !
    ! !ARGUMENTS:
    type(gridcell_nutrient_flux), intent(inout) :: this
    type(bounds_type), intent(in)  :: bounds 
    integer  :: g          ! indices
    !-----------------------------------------------------------------------
    !-----------------------------------------------------------------------

    ! set column-level conversion and product pool fluxes
    ! to 0 at the beginning of every timestep

    do g = bounds%begg, bounds%endg
       this%dwt_seed_to_leaf(g)         = 0._r8
       this%dwt_seed_to_deadstem(g)     = 0._r8
       this%dwt_conv_flux(g)            = 0._r8
       this%dwt_prod10_gain(g)          = 0._r8
       this%dwt_prod100_gain(g)         = 0._r8
    end do

  end subroutine gridcell_nutrient_flux_zerodwt

