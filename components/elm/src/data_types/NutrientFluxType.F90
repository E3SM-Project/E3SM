  subroutine column_nutrient_flux_init_history(this, begc, endc)
    !
    ! !DESCRIPTION:
    ! History fields of the core of column_carbon_flux, column_nitrogen_flux, column_phosphorus_flux:
    ! one hist_addfld1d per field for every species (generated by `spel nutrient history`)
    !
    ! !ARGUMENTS:
    type(column_nutrient_flux), intent(inout) :: this
    integer, intent(in) :: begc,endc
    !-----------------------------------------------------------------------

    if (use_fates) then
       if (this%species == CN_SPECIES_C12) then
          this%hrv_deadstem_to_prod10(begc:endc) = spval
          call hist_addfld1d (fname='HRV_DEADSTEMC_TO_PROD10C', units='gC/m^2/s', avgflag='A', &
               long_name='flux into 10-yr wood product C', ptr_col=this%hrv_deadstem_to_prod10, &
               default='inactive')

          this%hrv_deadstem_to_prod100(begc:endc) = spval
          call hist_addfld1d (fname='HRV_DEADSTEMC_TO_PROD100C', units='gC/m^2/s', avgflag='A', &
               long_name='flux into 100-yr wood product C', ptr_col=this%hrv_deadstem_to_prod100, &
               default='inactive')

       end if
    end if
    if (.not. (is_carbon(this%species) .and. use_fates)) then
       if (this%species == CN_SPECIES_C12 .or. this%species == CN_SPECIES_N .or. this%species == CN_SPECIES_P) then
          this%som_erode(begc:endc) = spval
          call hist_addfld1d (fname=nutrient_name(this%species, 'SOM#_ERO'), &
               units=nutrient_units(this%species, 'g#/m^2/s'), avgflag='A', &
               long_name=nutrient_text(this%species, 'SO# detachment'), ptr_col=this%som_erode, &
               default='inactive')

          this%som_deposit(begc:endc) = spval
          call hist_addfld1d (fname=nutrient_name(this%species, 'SOM#_DEP'), &
               units=nutrient_units(this%species, 'g#/m^2/s'), avgflag='A', &
               long_name=nutrient_text(this%species, 'SO# hillslope redeposition'), &
               ptr_col=this%som_deposit, default='inactive')

          this%som_yield(begc:endc) = spval
          call hist_addfld1d (fname=nutrient_name(this%species, 'SOM#_YLD'), &
               units=nutrient_units(this%species, 'g#/m^2/s'), avgflag='A', &
               long_name=nutrient_text(this%species, 'SO# erosional loss to inland waters'), &
               ptr_col=this%som_yield, default='inactive')

       end if
       this%fire_loss(begc:endc) = spval
       call hist_addfld1d (fname=nutrient_name(this%species, 'COL_FIRE_#LOSS'), &
            units=nutrient_units(this%species, 'g#/m^2/s'), avgflag='A', &
            long_name=by_species(this%species, 'total column-level fire C loss for non-peat fires outside land-type converted region', 'C13 total column-level fire C loss', 'C14 total column-level fire C loss', 'total column-level fire N loss', 'total column-level fire P loss'), &
            ptr_col=this%fire_loss, &
            default=hist_default(this%species == CN_SPECIES_C13 .or. this%species == CN_SPECIES_C14))

       if (this%species == CN_SPECIES_C12 .or. this%species == CN_SPECIES_N .or. this%species == CN_SPECIES_P) then
          this%fire_decomp_loss(begc:endc) = spval
          call hist_addfld1d (fname=nutrient_name(this%species, 'DECOMP_FIRE_#LOSS'), &
               units=nutrient_units(this%species, 'g#/m^2/s'), avgflag='A', &
               long_name=by_species(this%species, 'decomposable fire C loss for non-peat fires outside land-type converted region', '', '', 'fire N loss from decomposable pools', 'fire P loss of decomposable pools'), &
               ptr_col=this%fire_decomp_loss, default='inactive')

       end if
       this%dwt_slash_flux(begc:endc) = spval
       call hist_addfld1d (fname=nutrient_name(this%species, 'DWT_SLASH_#FLUX'), &
            units=nutrient_units(this%species, 'g#/m^2/s'), avgflag='A', &
            long_name=nutrient_text(this%species, 'slash # flux to litter and CWD due to land use'), &
            ptr_col=this%dwt_slash_flux)

       this%dwt_conv_flux(begc:endc) = spval
       call hist_addfld1d (fname=nutrient_name(this%species, 'DWT_CONV_#FLUX'), &
            units=nutrient_units(this%species, 'g#/m^2/s'), avgflag='A', &
            long_name=nutrient_text(this%species, 'conversion # flux (immediate loss to atm)'), &
            ptr_col=this%dwt_conv_flux, &
            default=hist_default(this%species == CN_SPECIES_C13 .or. this%species == CN_SPECIES_C14))

       this%dwt_prod10_gain(begc:endc) = spval
       call hist_addfld1d (fname=nutrient_name(this%species, 'DWT_PROD10#_GAIN'), &
            units=nutrient_units(this%species, 'g#/m^2/s'), avgflag='A', &
            long_name=by_species(this%species, 'landcover change-driven addition to 10-yr wood product pool', 'C13 addition to 10-yr wood product pool', 'C14 addition to 10-yr wood product pool', 'addition to 10-yr wood product pool', 'addition to 10-yr wood product pool'), &
            ptr_col=this%dwt_prod10_gain, &
            default=hist_default(this%species == CN_SPECIES_C13 .or. this%species == CN_SPECIES_C14))

       this%prod10_loss(begc:endc) = spval
       call hist_addfld1d (fname=nutrient_name(this%species, 'PROD10#_LOSS'), &
            units=nutrient_units(this%species, 'g#/m^2/s'), avgflag='A', &
            long_name=nutrient_text(this%species, 'loss from 10-yr wood product pool'), &
            ptr_col=this%prod10_loss, &
            default=hist_default(this%species == CN_SPECIES_C13 .or. this%species == CN_SPECIES_C14))

       this%dwt_prod100_gain(begc:endc) = spval
       call hist_addfld1d (fname=nutrient_name(this%species, 'DWT_PROD100#_GAIN'), &
